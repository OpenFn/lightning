// Writes STATUS.md from the last scenario run: for every annotation, which
// scenarios pass, fail or are skipped on today's Lightning, and which have no
// test yet. `./run` leaves one Playwright JSON report per group in
// assets/scenario-reports/; this reads them all.
//   node test/scenarios/status.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const reports = join(here, '../../scenario-reports');
if (!existsSync(reports)) {
  console.error(`No reports in ${reports}. Run ./test/scenarios/run first.`);
  process.exit(1);
}

// annotation -> id -> { status, where, error }
const byAnnotation = {};
const record = (annotation, id, entry) => {
  const ids = (byAnnotation[annotation] ??= {});
  // a shared scenario tested on several pages fails if any page fails
  if (!ids[id] || entry.status === 'failed') ids[id] = entry;
};

const walk = (suite, file) => {
  for (const s of suite.suites ?? []) walk(s, s.file ?? file);
  for (const spec of suite.specs ?? []) {
    const test = spec.tests.at(-1);
    const result = test?.results.at(-1);
    const status =
      test?.status === 'skipped'
        ? 'skipped'
        : result?.status === 'passed'
          ? 'passed'
          : 'failed';
    const error = (result?.error?.message ?? '')
      .replace(new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'g'), '')
      .split('\n')
      .find((l) => l.trim());
    const page = basename(spec.file ?? file, '.spec.ts');
    const shared = spec.title.match(/(shared-[a-z-]+)@(S\d+)/);
    const own = spec.title.match(/^@(S\d+)/);
    if (shared) record(shared[1], shared[2], { status, where: page, error });
    else if (own) record(page, own[1], { status, where: page, error });
  }
};
for (const f of readdirSync(reports).filter((f) => f.endsWith('.json')))
  for (const suite of JSON.parse(readFileSync(join(reports, f), 'utf8')).suites)
    walk(suite, suite.file);

// a shared scenario covered by a page's own test takes that test's result
for (const f of readdirSync(here).filter((f) => f.endsWith('.spec.ts'))) {
  const page = basename(f, '.spec.ts');
  const src = readFileSync(join(here, f), 'utf8');
  for (const m of src.matchAll(/\/\/ covers (shared-[a-z-]+)@(S\d+) with @(S\d+)/g)) {
    const entry = byAnnotation[page]?.[m[3]];
    if (entry) record(m[1], m[2], { ...entry, where: page });
  }
}

let untested = '';
try {
  execFileSync('node', [join(here, 'check-annotations.mjs')], { encoding: 'utf8' });
} catch (e) {
  untested = e.stdout;
}
for (const m of untested.matchAll(/^ {2}([\w-]+)@(S\d+): no test$/gm))
  record(m[1], m[2], { status: 'no test' });

const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
const count = (ids, s) => Object.values(ids).filter((e) => e.status === s).length;
const names = Object.keys(byAnnotation).sort();
const totals = ['passed', 'failed', 'skipped', 'no test'].map((s) =>
  names.reduce((n, a) => n + count(byAnnotation[a], s), 0)
);

let out = `# Scenario status

Generated by \`node test/scenarios/status.mjs\` after \`./test/scenarios/run\`. Don't edit by hand.

Run against Lightning at \`${sha}\` on ${new Date().toISOString().slice(0, 10)}.

Passing ${totals[0]} · failing ${totals[1]} · skipped ${totals[2]} · no test ${totals[3]}

| Annotation | Passing | Failing | Skipped | No test |
|---|---|---|---|---|
`;
for (const a of names) {
  const ids = byAnnotation[a];
  out += `| ${a} | ${count(ids, 'passed')} | ${count(ids, 'failed')} | ${count(ids, 'skipped')} | ${count(ids, 'no test')} |\n`;
}
out += '\n## Failing\n\n';
for (const a of names)
  for (const [id, e] of Object.entries(byAnnotation[a]).sort())
    if (e.status === 'failed')
      out += `- ${a} ${id}${e.where !== a ? ` (on ${e.where})` : ''}: ${e.error ?? 'no message'}\n`;

writeFileSync(join(here, 'STATUS.md'), out);
console.log(`STATUS.md: ${totals.join(' / ')} (passing / failing / skipped / no test)`);
