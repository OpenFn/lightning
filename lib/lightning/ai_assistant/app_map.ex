defmodule Lightning.AiAssistant.AppMap do
  @moduledoc """
  Loads the app map build artifact (`priv/app_map.json`) for inclusion in
  AI assistant payloads.

  The artifact is generated by `mix lightning.gen.app_map` from
  `LightningWeb.AppMap` and committed. Reading the file — rather than calling
  the web module — keeps the core→web layering intact; the committed JSON is
  the contract between the layers, and a staleness test in
  `test/lightning_web/app_map_test.exs` keeps it in sync with its source.
  """

  require Logger

  @persistent_term_key {__MODULE__, :app_map}

  @doc """
  The decoded app map: a list of page maps with `"id"`, `"path"`,
  `"description"`, etc.

  The artifact is read and decoded once, then memoized in `:persistent_term`.
  Returns `nil` (after logging a warning) when it is missing or malformed, so
  callers can omit the field rather than crash the chat.
  """
  @spec fetch() :: [map()] | nil
  def fetch do
    case :persistent_term.get(@persistent_term_key, :unset) do
      :unset ->
        app_map = load(Application.app_dir(:lightning, "priv/app_map.json"))
        :persistent_term.put(@persistent_term_key, app_map)
        app_map

      app_map ->
        app_map
    end
  end

  @doc """
  Reads and decodes the artifact at `path` without memoization.

  Exposed so the degraded path can be exercised in tests; use `fetch/0`
  everywhere else.
  """
  @spec load(Path.t()) :: [map()] | nil
  def load(path) do
    with {:ok, contents} <- File.read(path),
         {:ok, pages} when is_list(pages) <- Jason.decode(contents) do
      pages
    else
      error ->
        Logger.warning(
          "Could not load the app map from #{path} (#{inspect(error)}); " <>
            "sending AI assistant payloads without it. " <>
            "Run `mix lightning.gen.app_map` to regenerate the artifact."
        )

        nil
    end
  end
end
